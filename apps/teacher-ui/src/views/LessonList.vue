<template>
  <div class="lesson-list-view sport-ui">
    <div class="page-header">
      <RouterLink v-if="classGroup" :to="`/classes/${classGroup.id}`" class="back-button">← Zur Klasse</RouterLink>
      <Button v-else label="Zurück" icon="pi pi-arrow-left" severity="secondary" text @click="router.back()" />
      <div class="header-content">
        <div>
          <h2>Stunden {{ classGroup ? `- ${classGroup.name}` : '' }}</h2>
          <p class="page-description">Verwalten Sie Unterrichtsstunden und Anwesenheit</p>
        </div>
        <Button label="Neue Stunde" icon="pi pi-plus" @click="openCreateLesson" />
      </div>
    </div>

    <!-- Loading State -->
    <div v-if="loading" class="loading-state" role="status">
      <div class="spinner"></div>
      <p>Stunden werden geladen...</p>
    </div>

    <!-- Error State -->
    <div v-else-if="error" class="error-state">
      <p>{{ error }}</p>
      <Button label="Erneut versuchen" icon="pi pi-refresh" @click="loadData" />
    </div>

    <!-- Lessons -->
    <div v-else>
      <!-- Filters -->
      <section class="card app-card filters-card">
        <div class="filters">
          <div class="filter-group">
            <label for="class-filter" class="filter-label">Klasse:</label>
            <Select inputId="class-filter" :modelValue="selectedClassId"
              :options="classFilterOptions" optionLabel="label" optionValue="value" class="filter-select"
              @update:modelValue="value => { selectedClassId = value; void onClassChange() }" />
          </div>
          
          <div class="filter-group">
            <label for="subject-filter" class="filter-label">Fach:</label>
            <Select inputId="subject-filter" v-model="selectedSubjectId"
              :options="subjectFilterOptions" optionLabel="label" optionValue="value" class="filter-select" />
          </div>

          <div class="filter-group">
            <label for="date-from" class="filter-label">Von:</label>
            <input 
              id="date-from" 
              type="date" 
              v-model="dateFrom" 
              class="filter-input"
              @change="onDateFilterChange"
            />
          </div>
          
          <div class="filter-group">
            <label for="date-to" class="filter-label">Bis:</label>
            <input 
              id="date-to" 
              type="date" 
              v-model="dateTo" 
              class="filter-input"
              @change="onDateFilterChange"
            />
          </div>
        </div>

        <div class="auto-generation">
          <h4>Stundenlauf für Schuljahr anlegen</h4>
          <p class="auto-generation-hint">
            Legt automatisch Wochenstunden für die ausgewählte Kombination aus Klasse und Fach an. Feiertage und Ferien aus dem Kalender werden übersprungen.
          </p>
          <div class="auto-generation-controls">
            <div class="filter-group">
              <label for="auto-weekday" class="filter-label">Wochentag</label>
              <Select inputId="auto-weekday" v-model="autoGenerateWeekday" :options="weekdayOptions"
                optionLabel="label" optionValue="value" class="filter-select" />
            </div>
            <div class="filter-group">
              <label for="auto-start-time" class="filter-label">Startzeit</label>
              <InputText id="auto-start-time" v-model="autoGenerateStartTime" type="time" class="filter-input" />
            </div>
            <div class="filter-group">
              <label for="auto-duration" class="filter-label">Dauer (Minuten)</label>
              <input id="auto-duration" v-model.number="autoGenerateDuration" type="number" min="1" max="300" class="filter-input" />
            </div>
            <div class="filter-group filter-group-actions">
              <Button label="Stunden anlegen" severity="secondary" outlined
                :loading="autoGenerateBusy" :disabled="!selectedClassId || !selectedSubjectId || autoGenerateBusy"
                @click="handleAutoGenerateLessons" />
            </div>
          </div>
          <p
            v-if="autoGenerateStatus"
            :class="[
              'auto-generation-status',
              autoGenerateStatusType === 'error' ? 'auto-generation-status-error' : 'auto-generation-status-success'
            ]"
          >
            {{ autoGenerateStatus }}
          </p>
        </div>
      </section>

      <!-- Lessons List -->
      <section class="card">
        <h3>Stunden ({{ filteredLessons.length }})</h3>
        
        <div v-if="filteredLessons.length === 0" class="empty-state">
          <p>Keine Stunden gefunden. {{ selectedClassId ? 'Erstellen Sie die erste Stunde für diese Klasse.' : 'Wählen Sie eine Klasse und erstellen Sie eine Stunde.' }}</p>
        </div>
        
        <div v-else class="lessons-list">
          <div v-for="lesson in filteredLessons" :key="lesson.id" class="lesson-card">
            <div class="lesson-main">
              <div class="lesson-date">
                <div class="lesson-day">{{ formatDay(lesson.date) }}</div>
                <div class="lesson-month">{{ formatMonth(lesson.date) }}</div>
              </div>
              <div class="lesson-info">
                <h4>{{ getClassName(lesson.classGroupId) }} · {{ getSubjectName(lesson.subjectId) }}</h4>
                <p class="lesson-time">{{ lesson.startTime }} Uhr · {{ lesson.durationMinutes }} min{{ lesson.room ? ` · ${lesson.room}` : '' }}</p>
                <p v-if="lesson.title" class="lesson-title">{{ lesson.title }}</p>
                <div v-if="lesson.lessonParts && lesson.lessonParts.length > 0" class="lesson-parts">
                  <span v-for="(part, idx) in lesson.lessonParts" :key="part.id" class="lesson-part">
                    {{ part.description }}{{ idx < lesson.lessonParts!.length - 1 ? ', ' : '' }}
                  </span>
                </div>
                <div v-if="lesson.shortcuts && lesson.shortcuts.length > 0" class="lesson-shortcuts">
                  <span v-for="tag in lesson.shortcuts" :key="tag" class="lesson-shortcut-tag">{{ tag }}</span>
                </div>
              </div>
            </div>
            <div class="lesson-actions">
              <RouterLink 
                :to="`/lessons/${lesson.id}/workspace`"
                class="action-btn action-btn-workspace"
                title="Arbeitsbereich öffnen"
                aria-label="Arbeitsbereich öffnen"
              >
                →
              </RouterLink>
              <RouterLink 
                :to="`/attendance?classId=${lesson.classGroupId}&lessonId=${lesson.id}`" 
                class="action-btn action-btn-attendance"
                title="Anwesenheit erfassen"
                aria-label="Anwesenheit dieser Stunde öffnen"
              >
                ✓
              </RouterLink>
              <Button severity="secondary" text icon="pi pi-pencil" :aria-label="'Stunde bearbeiten'"
                @click="handleEditLesson(lesson)" />
              <Button severity="danger" text icon="pi pi-trash" :aria-label="'Stunde löschen'"
                @click="handleDeleteLesson(lesson.id)" />
            </div>
          </div>
        </div>
      </section>
    </div>

    <!-- Create/Edit Lesson Modal -->
    <Dialog :visible="showCreateLessonModal || showEditLessonModal" modal :closable="!saving"
      :header="showEditLessonModal ? 'Stunde bearbeiten' : 'Neue Stunde'"
      :style="{ width: '36rem', maxWidth: 'calc(100vw - 2rem)' }"
      @update:visible="visible => { if (!visible && !saving) closeModals() }">
        
        <div class="modal-content">
          <div class="form-group">
            <label for="lesson-class" class="form-label">Klasse*</label>
            <Select inputId="lesson-class" v-model="lessonForm.classGroupId"
              :options="lessonClassOptions" optionLabel="label" optionValue="value"
              placeholder="Klasse wählen" :disabled="showEditLessonModal" fluid />
          </div>
          
          <div class="form-group">
            <label for="lesson-subject" class="form-label">Fach*</label>
            <Select inputId="lesson-subject" v-model="lessonForm.subjectId" :options="lessonSubjectOptions"
              optionLabel="label" optionValue="value" placeholder="Fach wählen" fluid />
          </div>

          <div class="form-group">
            <label for="lesson-date" class="form-label">Datum*</label>
            <input 
              id="lesson-date" 
              type="date" 
              v-model="lessonForm.date" 
              class="form-input"
            />
          </div>
          
          <div class="form-group">
            <label for="lesson-time" class="form-label">Uhrzeit*</label>
            <input 
              id="lesson-time" 
              type="time" 
              v-model="lessonForm.startTime" 
              class="form-input"
            />
          </div>

          <div class="form-group">
            <label for="lesson-duration" class="form-label">Dauer (Minuten)*</label>
            <div class="duration-presets">
              <button
                v-for="preset in [45, 90]"
                :key="preset"
                type="button"
                class="btn-secondary duration-preset"
                :class="{ active: lessonForm.durationMinutes === preset }"
                @click="lessonForm.durationMinutes = preset"
              >{{ preset }} min</button>
            </div>
            <input
              id="lesson-duration"
              type="number"
              v-model.number="lessonForm.durationMinutes"
              class="form-input"
              min="1"
              max="300"
              step="1"
              required
            />
          </div>

          <div class="form-group">
            <label for="lesson-shortcuts" class="form-label">Kürzel / Tags</label>
            <input
              id="lesson-shortcuts"
              type="text"
              v-model="lessonForm.shortcuts"
              class="form-input"
              placeholder="z. B. Aufwärmen, Sprint (kommagetrennt)"
            />
          </div>

          <div class="form-group">
            <label class="form-label">Stundenteile</label>
            <div
              v-for="(part, idx) in lessonForm.lessonParts"
              :key="idx"
              class="lesson-part-row"
            >
              <input
                type="text"
                v-model="part.description"
                class="form-input lesson-part-description"
                placeholder="Beschreibung"
              />
              <input
                type="number"
                v-model="part.duration"
                class="form-input lesson-part-duration"
                placeholder="Min."
                min="1"
              />
              <button
                type="button"
                class="lesson-part-remove"
                @click="lessonForm.lessonParts.splice(idx, 1)"
                title="Teil entfernen"
              >×</button>
            </div>
            <button
              type="button"
              class="btn-secondary lesson-part-add"
              @click="lessonForm.lessonParts.push({ description: '', duration: '', type: '' })"
            >+ Stundenteil hinzufügen</button>
          </div>

          <div v-if="saveError" class="error-message">
            {{ saveError }}
          </div>
        </div>
        
        <div class="modal-footer">
          <Button label="Abbrechen" severity="secondary" :disabled="saving" @click="closeModals" />
          <Button :label="showEditLessonModal ? 'Speichern' : 'Erstellen'" :loading="saving"
            :disabled="!lessonForm.classGroupId || !lessonForm.subjectId || !lessonForm.date || !lessonForm.startTime || saving"
            @click="handleSaveLesson" />
        </div>
    </Dialog>
  </div>
</template>

<script setup lang="ts">
import { ref, computed, nextTick, onMounted } from 'vue'
import { RouterLink, useRoute, useRouter } from 'vue-router'
import Button from 'openvue/button'
import Dialog from 'openvue/dialog'
import InputText from 'openvue/inputtext'
import Select from 'openvue/select'
import { getSportBridge } from '../composables/useSportBridge'
import type { Lesson, ClassGroup, Subject } from '@viccoboard/core'
import { buildAutoLessonDates, getDateKey } from '../utils/lesson-auto-generation'
import { recordRouteContentReady } from '../utils/navigation-performance'

const route = useRoute()
const router = useRouter()
const SportBridge = getSportBridge()

// State
const classes = ref<ClassGroup[]>([])
const subjects = ref<Subject[]>([])
const lessons = ref<Lesson[]>([])
const classGroup = ref<ClassGroup | null>(null)
const loading = ref(false)
const saving = ref(false)
const error = ref('')
const saveError = ref('')
const selectedClassId = ref<string>(
  typeof route.query.classId === 'string' ? route.query.classId : ''
)
const selectedSubjectId = ref<string>('')
const dateFrom = ref<string>('')
const dateTo = ref<string>('')
const showCreateLessonModal = ref(false)
const showEditLessonModal = ref(false)
const autoGenerateWeekday = ref(1)
const autoGenerateStartTime = ref('08:00')
const autoGenerateDuration = ref(45)
const autoGenerateBusy = ref(false)
const autoGenerateStatus = ref('')
const autoGenerateStatusType = ref<'success' | 'error' | ''>('')

interface LessonPartForm {
  description: string
  duration: string
  type: string
}

interface LessonForm {
  id?: string
  classGroupId: string
  subjectId: string
  date: string
  startTime: string
  durationMinutes: number
  title: string
  room: string
  shortcuts: string
  lessonParts: LessonPartForm[]
}

const getInitialLessonForm = (): LessonForm => ({
  classGroupId: selectedClassId.value || '',
  subjectId: selectedSubjectId.value || '',
  date: new Date().toISOString().split('T')[0],
  startTime: '08:00',
  durationMinutes: 45,
  title: '',
  room: '',
  shortcuts: '',
  lessonParts: []
})

const lessonForm = ref<LessonForm>(getInitialLessonForm())

const lessonClassOptions = computed(() =>
  classes.value.map(group => ({ label: `${group.name} (${group.schoolYear})`, value: group.id }))
)
const classFilterOptions = computed(() => [
  { label: 'Alle Klassen', value: '' },
  ...lessonClassOptions.value
])
const lessonSubjectOptions = computed(() => subjects.value.map(subject => ({ label: subject.name, value: subject.id })))
const subjectFilterOptions = computed(() => [
  { label: 'Alle Fächer', value: '' },
  ...lessonSubjectOptions.value
])

const weekdayOptions = [
  { value: 1, label: 'Montag' },
  { value: 2, label: 'Dienstag' },
  { value: 3, label: 'Mittwoch' },
  { value: 4, label: 'Donnerstag' },
  { value: 5, label: 'Freitag' },
]

// Computed
const filteredLessons = computed(() => {
  let filtered = [...lessons.value]

  if (selectedClassId.value) {
    filtered = filtered.filter(l => l.classGroupId === selectedClassId.value)
  }

  if (selectedSubjectId.value) {
    filtered = filtered.filter(l => l.subjectId === selectedSubjectId.value)
  }

  if (dateFrom.value) {
    const fromDate = new Date(dateFrom.value)
    filtered = filtered.filter(l => l.date >= fromDate)
  }

  if (dateTo.value) {
    const toDate = new Date(dateTo.value)
    toDate.setHours(23, 59, 59, 999)
    filtered = filtered.filter(l => l.date <= toDate)
  }

  // Sort by date descending
  return filtered.sort((a, b) => b.date.getTime() - a.date.getTime())
})

// Methods
const enrichWithParts = async (lessonList: Lesson[]) => {
  for (const lesson of lessonList) {
    if (lessons.value !== lessonList) return
    try {
      lesson.lessonParts = await SportBridge.lessonPartRepository.findByLesson(lesson.id)
    } catch (err) {
      console.error('Failed to load lesson parts:', lesson.id, err)
    }
  }
}

let classChangeVersion = 0

const loadData = async () => {
  ++classChangeVersion
  loading.value = true
  error.value = ''

  try {
    const classIdFromRoute = typeof route.query.classId === 'string' ? route.query.classId : ''
    const classLessons = classIdFromRoute
      ? SportBridge.lessonRepository.findByClassGroup(classIdFromRoute)
      : Promise.resolve(null)
    const [loadedClasses, loadedSubjects, selectedLessons] = await Promise.all([
      SportBridge.classGroupRepository.findAll(),
      SportBridge.subjectRepository.findAll(),
      classLessons
    ])
    classes.value = loadedClasses
    subjects.value = loadedSubjects.sort((left, right) => left.name.localeCompare(right.name, 'de-DE'))

    if (classIdFromRoute) {
      const selectedClass = loadedClasses.find(group => group.id === classIdFromRoute)
      if (!selectedClass) throw new Error('Die angeforderte Klasse wurde nicht gefunden.')
      selectedClassId.value = selectedClass.id
      classGroup.value = selectedClass
      lessons.value = selectedLessons ?? []
    } else {
      lessons.value = (await Promise.all(
        loadedClasses.map(group => SportBridge.lessonRepository.findByClassGroup(group.id))
      )).flat()
    }
  } catch (err) {
    console.error('Failed to load lessons:', err)
    error.value = err instanceof Error ? err.message : 'Fehler beim Laden der Stunden'
  } finally {
    loading.value = false
  }
  if (!error.value) {
    await nextTick()
    recordRouteContentReady('lessons')
    void enrichWithParts(lessons.value)
  }
}

const onClassChange = async () => {
  const version = ++classChangeVersion
  const classId = selectedClassId.value
  autoGenerateStatus.value = ''
  autoGenerateStatusType.value = ''

  try {
    const loaded = classId
      ? await SportBridge.lessonRepository.findByClassGroup(classId)
      : (await Promise.all(
          classes.value.map(group => SportBridge.lessonRepository.findByClassGroup(group.id))
        )).flat()
    if (version !== classChangeVersion) return

    lessons.value = loaded
    classGroup.value = classes.value.find(group => group.id === classId) ?? null
    void enrichWithParts(lessons.value)
  } catch (err) {
    if (version === classChangeVersion) {
      console.error('Failed to change lesson class:', err)
      error.value = 'Stunden der gewählten Klasse konnten nicht geladen werden.'
    }
  }
}

const handleAutoGenerateLessons = async () => {
  autoGenerateStatus.value = ''
  autoGenerateStatusType.value = ''
  if (!selectedClassId.value || !selectedSubjectId.value) {
    autoGenerateStatus.value = 'Bitte zuerst Klasse und Fach auswählen.'
    autoGenerateStatusType.value = 'error'
    return
  }

  const selectedClass = classes.value.find((entry) => entry.id === selectedClassId.value)
  if (!selectedClass) {
    autoGenerateStatus.value = 'Klasse konnte nicht geladen werden.'
    autoGenerateStatusType.value = 'error'
    return
  }

  autoGenerateBusy.value = true
  try {
    const existingLessonDateKeys = new Set(
      lessons.value
        .filter((entry) =>
          entry.classGroupId === selectedClass.id && entry.subjectId === selectedSubjectId.value
        )
        .map((entry) => getDateKey(entry.date))
    )
    const dates = buildAutoLessonDates({
      schoolYear: selectedClass.schoolYear,
      weekday: autoGenerateWeekday.value,
      states: selectedClass.state ? [selectedClass.state] : [],
      existingLessonDateKeys
    })

    if (dates.length === 0) {
      autoGenerateStatus.value = 'Keine neuen Termine gefunden.'
      autoGenerateStatusType.value = 'success'
      return
    }

    const [hours, minutes] = autoGenerateStartTime.value.split(':').map((value) => Number(value))
    let created = 0
    for (const date of dates) {
      const lessonDate = new Date(date)
      lessonDate.setHours(hours || 0, minutes || 0, 0, 0)

      await SportBridge.createLessonUseCase.execute({
        classGroupId: selectedClass.id,
        subjectId: selectedSubjectId.value,
        date: lessonDate,
        startTime: autoGenerateStartTime.value,
        durationMinutes: autoGenerateDuration.value
      })
      created += 1
    }

    autoGenerateStatus.value = `${created} Stunden wurden angelegt.`
    autoGenerateStatusType.value = 'success'
    await loadData()
  } catch (err) {
    autoGenerateStatus.value = err instanceof Error ? err.message : 'Stunden konnten nicht automatisch angelegt werden.'
    autoGenerateStatusType.value = 'error'
  } finally {
    autoGenerateBusy.value = false
  }
}

const onDateFilterChange = () => {
  // Filtering happens automatically via computed property
}

const openCreateLesson = () => {
  lessonForm.value = getInitialLessonForm()
  showCreateLessonModal.value = true
}

const handleEditLesson = async (lesson: Lesson) => {
  const parts = await SportBridge.lessonPartRepository.findByLesson(lesson.id)
  lessonForm.value = {
    id: lesson.id,
    classGroupId: lesson.classGroupId,
    subjectId: lesson.subjectId,
    date: lesson.date.toISOString().split('T')[0],
    startTime: lesson.startTime || lesson.date.toTimeString().split(' ')[0].substring(0, 5),
    durationMinutes: lesson.durationMinutes,
    title: lesson.title || '',
    room: lesson.room || '',
    shortcuts: (lesson.shortcuts ?? []).join(', '),
    lessonParts: parts.map((part) => ({
      description: part.description,
      duration: part.duration !== undefined ? String(part.duration) : '',
      type: part.type ?? ''
    }))
  }
  showEditLessonModal.value = true
}

const handleDeleteLesson = async (lessonId: string) => {
  if (!confirm('Möchten Sie diese Stunde wirklich löschen?')) {
    return
  }

  try {
    await SportBridge.lessonRepository.delete(lessonId)
    await loadData()
  } catch (err) {
    console.error('Failed to delete lesson:', err)
    error.value = 'Fehler beim Löschen der Stunde'
  }
}

const handleSaveLesson = async () => {
  saveError.value = ''
  saving.value = true

  try {
    // Combine date and time for the lesson date field
    const dateTime = new Date(`${lessonForm.value.date}T${lessonForm.value.startTime}:00`)
    const shortcuts = parseShortcuts(lessonForm.value.shortcuts)
    const partsInput = lessonForm.value.lessonParts
      .filter((part) => part.description.trim().length > 0)
      .map((part) => ({
        description: part.description.trim(),
        duration: part.duration ? Number(part.duration) : undefined,
        type: part.type.trim() || undefined
      }))

    let createdLessonId: string | null = null
    if (showEditLessonModal.value && lessonForm.value.id) {
      // Update existing lesson via validated use-case
      await SportBridge.updateLessonUseCase.execute({
        lessonId: lessonForm.value.id,
        subjectId: lessonForm.value.subjectId,
        date: dateTime,
        startTime: lessonForm.value.startTime,
        durationMinutes: lessonForm.value.durationMinutes,
        title: lessonForm.value.title.trim() || undefined,
        room: lessonForm.value.room.trim() || undefined,
        shortcuts
      })
      await SportBridge.lessonPartRepository.replacePartsForLesson(lessonForm.value.id, partsInput)
    } else {
      // Create new lesson
      const created = await SportBridge.createLessonUseCase.execute({
        classGroupId: lessonForm.value.classGroupId,
        subjectId: lessonForm.value.subjectId,
        date: dateTime,
        startTime: lessonForm.value.startTime,
        durationMinutes: lessonForm.value.durationMinutes,
        title: lessonForm.value.title.trim() || undefined,
        room: lessonForm.value.room.trim() || undefined,
        shortcuts
      })
      await SportBridge.lessonPartRepository.replacePartsForLesson(created.id, partsInput)
      createdLessonId = created.id
    }

    closeModals()
    if (createdLessonId) {
      await router.push(`/lessons/${createdLessonId}/workspace`)
    } else {
      await loadData()
    }
  } catch (err) {
    console.error('Failed to save lesson:', err)
    if (err instanceof Error) {
      saveError.value = err.message
    } else {
      saveError.value = 'Fehler beim Speichern der Stunde'
    }
  } finally {
    saving.value = false
  }
}

const closeModals = () => {
  showCreateLessonModal.value = false
  showEditLessonModal.value = false
  saveError.value = ''
  lessonForm.value = getInitialLessonForm()
}

const parseShortcuts = (value: string): string[] =>
  value
    .split(',')
    .map((shortcut) => shortcut.trim())
    .filter((shortcut) => shortcut.length > 0)

const getClassName = (classGroupId: string): string => {
  const cls = classes.value.find(c => c.id === classGroupId)
  return cls ? cls.name : 'Unbekannt'
}

const getSubjectName = (subjectId: string): string =>
  subjects.value.find((subject) => subject.id === subjectId)?.name ?? 'Unzugeordnet'

const formatDay = (date: Date): string => {
  return date.getDate().toString().padStart(2, '0')
}

const formatMonth = (date: Date): string => {
  const months = ['Jan', 'Feb', 'Mär', 'Apr', 'Mai', 'Jun', 'Jul', 'Aug', 'Sep', 'Okt', 'Nov', 'Dez']
  return months[date.getMonth()]
}

// Lifecycle
onMounted(async () => {
  await loadData()
})
</script>

